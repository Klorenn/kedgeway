export type PixelIconName = keyof typeof SPRITES;

for (const [name, rows] of Object.entries(SPRITES)) {
  if (rows.length !== 16 || rows.some((r) => r.length !== 16)) throw new Error(`pixel icon "${name}" is not 16x16`);
}

interface PixelIconProps {
  name: PixelIconName;
  /** Rendered size in px (a multiple of 16 stays crisp). */
  size?: number;
  /** Accessible name. Omit for decorative icons (aria-hidden). */
  title?: string;
}

export default function PixelIcon({ name, size = 16, title }: PixelIconProps): ReactNode {
  const rows: readonly string[] = SPRITES[name];
  const rects: ReactNode[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < 16) {
      if (row[x] === "#") {
        let e = x;
        while (e < 16 && row[e] === "#") e++;
        rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={e - x} height={1} />);
        x = e;
      } else x++;
    }
  });
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      fill="currentColor"
      shapeRendering="crispEdges"
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
      style={{ display: "block", flex: "none" }}
    >
      {title ? <title>{title}</title> : null}
      {rects}
    </svg>
  );
}
