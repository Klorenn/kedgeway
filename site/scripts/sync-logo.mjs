// Reads design/logo/mark.svg and writes src/components/ui/logo-mark.generated.ts (viewBox + path data).
// Run: node scripts/sync-logo.mjs   (also runs automatically as `prebuild`/`predev` when the SVG exists).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "design/logo/mark.svg");
const out = join(root, "src/components/ui/logo-mark.generated.ts");

if (!existsSync(src)) {
  console.warn("sync-logo: design/logo/mark.svg not found, keeping existing generated file");
  process.exit(0);
}
const svg = readFileSync(src, "utf8");
const vb = /viewBox="([^"]+)"/.exec(svg)?.[1];
const paths = [...svg.matchAll(/<path\b[^>]*?\sd="([^"]+)"[^>]*>/g)].map((m) => m[1]);
if (!vb || paths.length === 0) {
  console.error("sync-logo: could not parse viewBox/path from mark.svg");
  process.exit(1);
}
const [, , w, h] = vb.split(/[\s,]+/).map(Number);
const body =
  `// GENERATED by scripts/sync-logo.mjs from design/logo/mark.svg. Do not edit.\n` +
  `export const LOGO_PLACEHOLDER = false;\n` +
  `export const LOGO_VIEWBOX = ${JSON.stringify(vb)};\n` +
  `export const LOGO_ASPECT = ${w / h};\n` +
  `export const LOGO_PATHS: readonly string[] = ${JSON.stringify(paths)};\n`;
writeFileSync(out, body);
console.log(`sync-logo: wrote ${out} (${paths.length} path(s))`);
