// Inlines design/figures/*.svg, design/gallop/frame-NN.svg and design/ascii/*.txt into generated TypeScript.
//   src/generated/figures.generated.ts  { name: { desktop?: {w,h,viewBox,inner}, mobile?: {...} } }
//   src/generated/frames.generated.ts   11 gallop frame inner markup strings (viewBox 0 0 180 101)
//   src/generated/ascii.generated.ts    one exported string per .txt file
// A missing required file fails the build with a clear message. Colour fallbacks (var(--color-x,#hex)) are stripped,
// so figures reference tokens only.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const design = join(root, "design");
const out = join(root, "src/generated");
mkdirSync(out, { recursive: true });

const FIGURES = {
  textureGround: "texture-ground",
  plateIndex: null, // not inlined: the plate is built from frames + HTML ruler
  fig2: "fig-2-ecosystem-field",
  fig3: "fig-3-pipeline",
  fig4: "fig-4-report-anatomy",
  fig5: "fig-5-severity-scale",
  fig6: "fig-6-install-timeline",
  fig7: "fig-7-cloud-study",
  fig8: "fig-8-integrations-hub",
};
const ASCII = ["stats", "findings", "terminal", "gallop"];

const missing = [];
const need = (rel) => {
  const p = join(design, rel);
  if (!existsSync(p)) {
    missing.push(`design/${rel}`);
    return null;
  }
  return readFileSync(p, "utf8");
};

function parseSvg(src, rel) {
  const root = /<svg\b([^>]*)>/.exec(src);
  if (!root) throw new Error(`sync-design: ${rel} is not an SVG`);
  const attrs = root[1];
  const viewBox = /viewBox="([^"]+)"/.exec(attrs)?.[1];
  const w = Number(/\swidth="([\d.]+)"/.exec(attrs)?.[1]);
  const h = Number(/\sheight="([\d.]+)"/.exec(attrs)?.[1]);
  if (!viewBox || !w || !h) throw new Error(`sync-design: ${rel} needs viewBox, width and height`);
  let inner = src.slice(root.index + root[0].length, src.lastIndexOf("</svg>")).trim();
  inner = inner.replace(/var\((--color-[a-z0-9-]+),\s*#[0-9a-fA-F]{3,8}\)/g, "var($1)");
  const hex = inner.match(/#[0-9a-fA-F]{6}\b/g);
  if (hex) throw new Error(`sync-design: ${rel} still contains hard-coded colour ${hex[0]}; export with tokens or currentColor`);
  return { w, h, viewBox, inner };
}

const figures = {};
for (const [key, base] of Object.entries(FIGURES)) {
  if (!base) continue;
  figures[key] = {};
  for (const size of ["desktop", "mobile"]) {
    const rel = `figures/${base}-${size}.svg`;
    const src = need(rel);
    if (src) figures[key][size] = parseSvg(src, rel);
  }
}
const frames = [];
for (let i = 1; i <= 11; i++) {
  const rel = `gallop/frame-${String(i).padStart(2, "0")}.svg`;
  const src = need(rel);
  if (src) frames.push(parseSvg(src, rel).inner);
}
const ascii = {};
const lead = {};
for (const name of ASCII) {
  for (const size of ["desktop", "mobile"]) {
    const src = need(`ascii/${name}-${size}.txt`);
    if (src === null) continue;
    const key = `${name}${size === "desktop" ? "Desktop" : "Mobile"}`;
    // The HTML parser drops a newline right after <pre>, which breaks hydration. So the text never starts with one:
    // leading blank lines are removed here and exported as a count; AsciiBlock restores them as padding-top.
    const lines = src.replace(/\n$/, "").split("\n");
    let n = 0;
    while (n < lines.length - 1 && lines[n].trim() === "") n++;
    ascii[key] = lines.slice(n).join("\n");
    lead[`${key}Lead`] = n;
  }
}

if (missing.length) {
  console.error(`\nsync-design: missing design assets (the figma-exporter must write these):\n  ${missing.join("\n  ")}\n`);
  process.exit(1);
}

const head = "// GENERATED by scripts/sync-design.mjs from design/. Do not edit.\n";
// One module per figure so the big stipple SVGs are code-split and loaded on demand (see LazyDesignFigure),
// plus a tiny dimensions module the server can read to reserve each figure's box.
writeFileSync(join(out, "figure-types.ts"), `${head}export interface FigureSvg { w: number; h: number; viewBox: string; inner: string }\nexport interface FigureSet { desktop: FigureSvg; mobile: FigureSvg }\n`);
const dims = {};
for (const [key, set] of Object.entries(figures)) {
  writeFileSync(join(out, `${key}.generated.ts`), `${head}import type { FigureSet } from "./figure-types";\nconst fig: FigureSet = ${JSON.stringify(set)};\nexport default fig;\n`);
  dims[key] = { desktop: [set.desktop.w, set.desktop.h], mobile: [set.mobile.w, set.mobile.h] };
}
writeFileSync(join(out, "figure-dims.generated.ts"), `${head}export const FIGURE_DIMS = ${JSON.stringify(dims)} as const;\nexport type FigureName = keyof typeof FIGURE_DIMS;\n`);
writeFileSync(join(out, "frames.generated.ts"), `${head}export const FRAME_VIEWBOX = "0 0 180 101";\nexport const FRAMES: readonly string[] = ${JSON.stringify(frames)};\n`);
writeFileSync(
  join(out, "ascii.generated.ts"),
  head +
    Object.entries(ascii).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};\n`).join("") +
    Object.entries(lead).map(([k, v]) => `export const ${k} = ${v}; // blank lines removed from the top\n`).join(""),
);
console.log(`sync-design: ${Object.keys(figures).length} figures, ${frames.length} frames, ${Object.keys(ascii).length} ascii files`);
